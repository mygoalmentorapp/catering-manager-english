type TranslationKey = keyof (typeof translations)["he"];

/**
 * Hook-like function to get the translation function for a given language.
 * Usage: const t = useT(selectedLanguage);
 *        t("nav.dashboard") => "סקירה כללית"
 */
export function getT(lang: string): (key: TranslationKey) => string {
  const dict = lang === "he" ? translations.he : translations.en;
  return (key: TranslationKey) => dict[key] ?? key;
}

/**
 * Get a module label in the current language
 */
export function getModuleLabel(moduleKey: string, lang: string): string {
  const dict = lang === "he" ? translations.he : translations.en;
  const key = `module.${moduleKey}` as TranslationKey;
  return dict[key] ?? moduleKey;
}

/**
 * Get a language label in the current language
 */
export function getLanguageLabel(langCode: string, currentLang: string): string {
  const dict = currentLang === "he" ? translations.he : translations.en;
  const key = `lang.${langCode}` as TranslationKey;
  return dict[key] ?? langCode;
}
